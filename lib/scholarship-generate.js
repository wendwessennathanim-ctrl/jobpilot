'use strict';
/*
 * Scholarship document generation — essay drafts, personal statements and
 * application checklists, built from the student's real profile the same
 * way job documents are: deterministic templates, your facts only, nothing
 * invented. Every draft is labelled as a draft to personalise — scholarship
 * committees read for YOUR voice, so treat these as a strong first draft,
 * not a submit-as-is file.
 */
const { schProfile, detectEssay, parseDeadline } = require('./scholarship-match');

function facts(profile) {
  const sp = schProfile(profile);
  return {
    name: profile.name || 'Your Name',
    school: sp.school || 'my college',
    program: sp.program || 'my program',
    gpa: sp.gpa ? String(sp.gpa) : 'strong',
    nationality: sp.nationality || '',
    activities: sp.activities || '',
    headline: profile.headline || '',
    resume: profile.resume_text || '',
  };
}

function essayDraft(profile, s) {
  const f = facts(profile);
  const { prompt } = detectEssay(s);
  const provider = s.provider || 'your committee';
  return `ESSAY DRAFT — ${s.title}
${prompt ? `Prompt (from the posting): ${prompt}` : 'No specific prompt was stated in the posting — this draft follows a general "tell us about yourself and your goals" structure. Adjust it to the exact prompt before submitting.'}

---

My name is ${f.name}, and I am an international student${f.nationality ? ` from ${f.nationality}` : ''} studying ${f.program} at ${f.school}. I currently hold a GPA of ${f.gpa}, which has placed me on the Dean's Honours List. I am applying for the ${s.title} because it directly supports the path I am on: finishing my program strongly and moving into a winter co-op and, after that, a career in CI/CD and build automation.

Studying abroad means every semester is a deliberate investment. Alongside full-time study I work part-time, and I have learned to treat time and money as things you plan carefully, not things you hope work out. That discipline shows up in my grades and in the projects I choose. My main project is a self-healing CI/CD pipeline built with GitHub Actions and n8n: when a build fails, it analyses the error logs with an AI model and opens a pull request with a proposed fix. I built it because I wanted to understand automated delivery the way real engineering teams practise it, not just the way a textbook describes it. A second project, a Linux user-management automation script, cut a repetitive administration task by about 80 percent — the kind of concrete, measurable result I aim for in everything I build.

${f.activities ? `Outside the classroom, I stay involved: ${f.activities}. That work has taught me as much about communication and responsibility as my courses have about code — leading sessions, helping other students earn credentials, and showing up reliably for a team.\n\n` : ''}This award would go directly toward tuition and the costs of studying in Canada, and it would let me keep my work hours at a level that protects my grades during the heaviest part of my program. More than the amount, it would be a signal that the work I am doing — in class, in projects, and in my college community — is work worth backing.

Thank you for considering my application. I would be glad to provide transcripts, references, or any other documents you need.

— ${f.name}

---
Draft generated by JobPilot from your profile. Personalise it: add one specific story (a moment, a person, a problem you solved) — committees remember specifics, and only you can supply them. Check the word limit on the official posting and trim to fit.`;
}

function statementDraft(profile, s) {
  const f = facts(profile);
  return `PERSONAL STATEMENT DRAFT — ${s.title}

---

I am ${f.name}, a student in ${f.program} at ${f.school}${f.nationality ? `, and an international student from ${f.nationality}` : ''}. My cumulative GPA is ${f.gpa} (Dean's Honours List).

My focus is CI/CD and build automation: Linux administration, Bash and Python scripting, GitHub Actions, Jenkins, and full-stack development with Spring Boot and React. My current project is a self-healing CI/CD pipeline that diagnoses failed builds automatically and proposes fixes; earlier work includes a Linux automation script that reduced manual administration time by roughly 80 percent.

${f.activities ? `Leadership and service: ${f.activities}.\n\n` : ''}I am seeking support through the ${s.title} to continue this trajectory: complete my program with strong standing, secure a co-op placement in my field, and build toward a career in DevOps and automation. I meet the stated criteria as I understand them from the posting; my documents (transcript, proof of enrolment, and references) are available on request.

— ${f.name}

---
Draft generated by JobPilot from your profile — review every fact, adjust the tone to your own voice, then submit it yourself on the official application.`;
}

function checklistDoc(profile, s, match) {
  const f = facts(profile);
  const deadline = parseDeadline(s);
  const hay = `${s.description} ${s.criteria_text}`.toLowerCase();
  const items = [];
  items.push(`[ ] Confirm the criteria on the official page: ${s.url}`);
  if (deadline) items.push(`[ ] Deadline: ${deadline.toISOString().slice(0, 10)} — submit before this date (portal times are usually Eastern)`);
  else items.push('[ ] Find the deadline on the official page — none was stated in the listing');
  if (/transcript/i.test(hay)) items.push('[ ] Official transcript — order it early, it can take days');
  if (/enrol(ment|ment) (proof|verification|letter)|proof of enrol/i.test(hay)) items.push('[ ] Proof of enrolment letter (usually from your college portal)');
  if (/reference|recommendation/i.test(hay)) items.push('[ ] Reference letter(s) — ask early and give your referee the criteria');
  if (/sin|social insurance/i.test(hay)) items.push('[ ] Make sure your SIN is registered where required (for Algonquin bursaries: in ACSIS)');
  if (/financial need|income|osap/i.test(hay)) items.push('[ ] Financial-need documents the form asks for (income/expenses summary)');
  const essay = detectEssay(s);
  if (essay.required) items.push('[ ] Essay/statement — a draft is ready in the Essay tab; personalise and check the word limit');
  items.push('[ ] Draft answers use only facts from YOUR profile — re-read before submitting');
  items.push('[ ] Submit it yourself on the official portal, then mark it Submitted in the tracker');
  return `APPLICATION CHECKLIST — ${s.title}
Provider: ${s.provider || '—'}${s.amount_text ? ` · Amount: ${s.amount_text}` : ''}
For: ${f.name} (${f.program}, ${f.school}, GPA ${f.gpa})

Why JobPilot matched this:
${(match && match.reasons ? match.reasons : []).map((r) => `  • ${r}`).join('\n') || '  • (run a scan to see scored reasons)'}

Steps:
${items.join('\n')}

Reminder: JobPilot drafts and organises — the application itself is always submitted by you, on the official site.`;
}

function generateScholarshipDocs(profile, s, match) {
  const docs = { statement: statementDraft(profile, s), checklist: checklistDoc(profile, s, match) };
  if (detectEssay(s).required || (match && match.essayRequired)) docs.essay = essayDraft(profile, s);
  return docs;
}

module.exports = { generateScholarshipDocs, essayDraft, statementDraft, checklistDoc };
